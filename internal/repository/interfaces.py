from typing import List
"""Контракты репозиториев. Сервисы зависят от этих интерфейсов, а не от SQL."""
from typing import Protocol, Optional
from internal.domain.models import User, Subject, Attendance

class UserRepository(Protocol):
    def create(self, user: User) -> User: ...
    def get_by_id(self, user_id: str) -> User: ...
    def get_by_email(self, email: str) -> User: ...
    def list(self, limit: int = 20, offset: int = 0) -> List[User]: ...
    def delete(self, user_id: str) -> None: ...

class SubjectRepository(Protocol):
    def create(self, subject: Subject) -> Subject: ...
    def get_by_id(self, subject_id: str) -> Subject: ...
    def list(self, limit: int = 20, offset: int = 0) -> List[Subject]: ...
    def update(self, subject: Subject) -> None: ...
    def delete(self, subject_id: str) -> None: ...

class AttendanceRepository(Protocol):
    def create(self, attendance: Attendance) -> Attendance: ...
    def get_by_id(self, attendance_id: str) -> Attendance: ...
    def list(self, limit: int = 20, offset: int = 0) -> List[Attendance]: ...
    def update(self, attendance: Attendance) -> None: ...
    def delete(self, attendance_id: str) -> None: ...
